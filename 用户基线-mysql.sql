CREATE TABLE IF NOT EXISTS `ra_user_baseline_detail` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键及追踪ID',
    `run_id` BIGINT NOT NULL COMMENT '每日运行ID',
    `data_date` DATE NOT NULL COMMENT '业务日期',
    `slot_no` TINYINT UNSIGNED NOT NULL COMMENT '点序号1至96',
    `target_time` DATETIME NOT NULL COMMENT '目标时刻',
    `cons_no` VARCHAR(64) NOT NULL COMMENT '户号',
    `unit_id` VARCHAR(64) DEFAULT NULL COMMENT '计算时所属单元，仅用于排除参与日期',
    `day_type` VARCHAR(16) NOT NULL COMMENT 'WORKDAY/RESTDAY/HOLIDAY',
    `sample_detail_json` JSON DEFAULT NULL COMMENT '典型样本及来源明细',
    `initial_mean_mw` DECIMAL(24,12) DEFAULT NULL COMMENT '剔除前初始均值',
    `threshold_mw` DECIMAL(24,12) DEFAULT NULL COMMENT '异常高值阈值',
    `removed_sample_json` JSON DEFAULT NULL COMMENT '被剔除样本明细',
    `removed_count` SMALLINT NOT NULL DEFAULT 0 COMMENT '被剔除样本数',
    `raw_baseline_calc_mw` DECIMAL(24,12) DEFAULT NULL COMMENT '未截断原始基线计算值，仅供最终基线计算',
    `raw_baseline_mw` DECIMAL(24,6) DEFAULT NULL COMMENT '原始基线B0',
    `need_correction` BIT(1) NOT NULL DEFAULT b'0' COMMENT '是否需要计算K修正',
    `actual_window_json` JSON DEFAULT NULL COMMENT '实际负荷窗口及补值来源',
    `baseline_window_json` JSON DEFAULT NULL COMMENT '历史最终基线窗口及来源',
    `actual_window_mean_mw` DECIMAL(24,6) DEFAULT NULL COMMENT '实际负荷窗口均值',
    `baseline_window_mean_mw` DECIMAL(24,6) DEFAULT NULL COMMENT '历史基线窗口均值',
    `k_value` DECIMAL(24,6) DEFAULT NULL COMMENT 'K值',
    `final_baseline_mw` DECIMAL(24,6) DEFAULT NULL COMMENT '最终基线',
    `correction_status` VARCHAR(32) NOT NULL COMMENT '修正状态',
    `calculation_remark` TEXT NOT NULL COMMENT '中文计算说明',
    `trace_code` VARCHAR(64) NOT NULL COMMENT '跨MySQL和TDengine追踪编码',
    `snapshot_time` DATETIME(3) NOT NULL COMMENT '数据快照时间',
    `generated_at` DATETIME(3) NOT NULL COMMENT '原始基线生成时间',
    `corrected_at` DATETIME(3) DEFAULT NULL COMMENT '修正完成时间',
    `sync_status` VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'TDengine同步状态：PENDING/SYNCED',
    `synced_at` DATETIME(3) DEFAULT NULL COMMENT '最近一次TDengine同步完成时间',
    `calc_version` VARCHAR(32) NOT NULL COMMENT '算法版本',
    `create_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    `create_by` BIGINT DEFAULT NULL COMMENT '创建人ID',
    `create_name` VARCHAR(64) DEFAULT NULL COMMENT '创建人姓名',
    `last_modify_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后修改时间',
    `last_modify_by` BIGINT DEFAULT NULL COMMENT '更新人ID',
    `last_modify_name` VARCHAR(64) DEFAULT NULL COMMENT '更新人姓名',
    `deleted` BIT(1) NOT NULL DEFAULT b'0' COMMENT '逻辑删除',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_user_baseline_detail` (`data_date`, `cons_no`, `slot_no`, `calc_version`),
    UNIQUE KEY `uk_user_baseline_trace` (`trace_code`),
    KEY `idx_user_baseline_waiting` (`data_date`, `slot_no`, `correction_status`, `id`),
    KEY `idx_user_baseline_sync` (`data_date`, `slot_no`, `sync_status`, `id`),
    KEY `idx_user_baseline_cons` (`cons_no`, `data_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户逐点基线计算审计明细';

