CREATE TABLE IF NOT EXISTS `ra_calendar_day` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
    `calendar_date` DATE NOT NULL COMMENT '日历日期',
    `day_type` VARCHAR(16) NOT NULL COMMENT '日期类型：WORKDAY/RESTDAY/HOLIDAY',
    `is_off_day` BIT(1) NOT NULL DEFAULT b'0' COMMENT '是否休息日',
    `is_adjusted_workday` BIT(1) NOT NULL DEFAULT b'0' COMMENT '是否调休工作日',
    `holiday_name` VARCHAR(128) DEFAULT NULL COMMENT '节假日中文名称',
    `holiday_code` VARCHAR(64) DEFAULT NULL COMMENT '节假日编码，允许人工维护',
    `holiday_group_code` VARCHAR(64) DEFAULT NULL COMMENT '连休假期组编码，允许人工维护',
    `festival_tags` VARCHAR(256) DEFAULT NULL COMMENT '具体日期的节日标签，多个标签使用英文逗号分隔',
    `source_url` VARCHAR(500) DEFAULT NULL COMMENT '来源地址',
    `source_version` VARCHAR(64) DEFAULT NULL COMMENT '来源版本',
    `source_hash` VARCHAR(64) DEFAULT NULL COMMENT '来源SHA-256',
    `manual_override` BIT(1) NOT NULL DEFAULT b'0' COMMENT '是否人工覆盖；同步任务不得覆盖',
    `remark` VARCHAR(1000) DEFAULT NULL COMMENT '中文备注',
    `create_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    `create_by` BIGINT DEFAULT NULL COMMENT '创建人ID',
    `create_name` VARCHAR(64) DEFAULT NULL COMMENT '创建人姓名',
    `last_modify_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后修改时间',
    `last_modify_by` BIGINT DEFAULT NULL COMMENT '最后修改人ID',
    `last_modify_name` VARCHAR(64) DEFAULT NULL COMMENT '最后修改人姓名',
    `deleted` BIT(1) NOT NULL DEFAULT b'0' COMMENT '逻辑删除',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_calendar_date` (`calendar_date`),
    KEY `idx_day_type_date` (`day_type`, `calendar_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户基线日历';

CREATE TABLE IF NOT EXISTS `ra_user_baseline_run` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
    `data_date` DATE NOT NULL COMMENT '业务日期',
    `calc_version` VARCHAR(32) NOT NULL COMMENT '算法版本',
    `status` VARCHAR(32) NOT NULL COMMENT '运行状态',
    `total_user_count` INT NOT NULL DEFAULT 0 COMMENT '总户数',
    `success_user_count` INT NOT NULL DEFAULT 0 COMMENT '成功户数',
    `failed_user_count` INT NOT NULL DEFAULT 0 COMMENT '失败户数',
    `snapshot_time` DATETIME(3) NOT NULL COMMENT '计算快照时间',
    `started_at` DATETIME(3) NOT NULL COMMENT '开始时间',
    `finished_at` DATETIME(3) DEFAULT NULL COMMENT '完成时间',
    `error_message` TEXT DEFAULT NULL COMMENT '中文错误说明',
    `execution_owner` VARCHAR(64) DEFAULT NULL COMMENT '当前执行者唯一标识',
    `lease_expire_time` DATETIME(3) DEFAULT NULL COMMENT '当前执行租约到期时间',
    `heartbeat_time` DATETIME(3) DEFAULT NULL COMMENT '当前执行者最近心跳时间',
    `create_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
    `create_by` BIGINT DEFAULT NULL COMMENT '创建人ID',
    `create_name` VARCHAR(64) DEFAULT NULL COMMENT '创建人姓名',
    `last_modify_time` DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '最后修改时间',
    `last_modify_by` BIGINT DEFAULT NULL COMMENT '更新人ID',
    `last_modify_name` VARCHAR(64) DEFAULT NULL COMMENT '更新人姓名',
    `deleted` BIT(1) NOT NULL DEFAULT b'0' COMMENT '逻辑删除',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_user_baseline_run` (`data_date`, `calc_version`),
    KEY `idx_user_baseline_run_status` (`status`, `data_date`),
